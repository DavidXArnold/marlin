// PreServeMount is where a profile's pre_serve script is mounted in the container.
const PreServeMount = "/marlin/pre-serve.sh"

// ExpandContext supplies the host values that profile placeholders resolve to.
type ExpandContext struct {
	Home    string // the invoking user's home directory
	HFCache string // host Hugging Face cache (see ResolveHFCache)
}

// NewExpandContext builds an ExpandContext for the current host.
func NewExpandContext(cfg *config.Config) ExpandContext {
	home, _ := os.UserHomeDir()
	if sudoUser := os.Getenv("SUDO_USER"); sudoUser != "" {
		if h, err := lookupUserHomeFunc(sudoUser); err == nil {
			home = h
		}
	}
	return ExpandContext{Home: home, HFCache: ResolveHFCache(cfg)}
}

var placeholder = regexp.MustCompile(`\{(home|hf_cache|hf_snapshot:[^{}\s]+)\}`)

// Expand resolves placeholders in s:
//
//	{home}               the invoking user's home directory
//	{hf_cache}           the host Hugging Face cache (paths.hf_cache)
//	{hf_snapshot:<repo>} the snapshot directory <repo>'s "main" ref points at in
//	                     that cache, so paths follow model updates
//
// Anything else in braces (e.g. JSON in a flag) is left untouched.
func Expand(s string, x ExpandContext) (string, error) {
	var firstErr error
	out := placeholder.ReplaceAllStringFunc(s, func(tok string) string {
		name := tok[1 : len(tok)-1]
		switch name {
		case "home":
			return x.Home
		case "hf_cache":
			return x.HFCache
		default:
			dir, err := hfSnapshotDir(x.HFCache, strings.TrimPrefix(name, "hf_snapshot:"))
			if err != nil && firstErr == nil {
				firstErr = err
			}
			return dir
		}
	})
	return out, firstErr
}

func hfSnapshotDir(hfCache, repo string) (string, error) {
	repoDir := filepath.Join(hfCache, "hub", "models--"+strings.ReplaceAll(repo, "/", "--"))
	ref, err := os.ReadFile(filepath.Join(repoDir, "refs", "main"))
	if err != nil {
		return "", fmt.Errorf("{hf_snapshot:%s}: not in the Hugging Face cache at %s — download it first (hf download %s)", repo, hfCache, repo)
	}
	snap := filepath.Join(repoDir, "snapshots", strings.TrimSpace(string(ref)))
	if _, err := os.Stat(snap); err != nil {
		return "", fmt.Errorf("{hf_snapshot:%s}: snapshot %s is missing — re-run the download", repo, snap)
	}
	return snap, nil
}

// ExpandModel returns a copy of m with placeholders resolved in the [container]
// table and serve.extra_flags. On error the copy is still returned, with every
// placeholder that could be resolved expanded, so previews stay readable.
func ExpandModel(m *config.ModelConfig, x ExpandContext) (*config.ModelConfig, error) {
	var err error
	one := func(s string) string {
		v, e := Expand(s, x)
		if e != nil && err == nil {
			err = e
		}
		return v
	}
	all := func(in []string) []string {
		if len(in) == 0 {
			return in
		}
		res := make([]string, len(in))
		for i, s := range in {
			res[i] = one(s)
		}
		return res
	}

	out := *m
	out.Serve.ExtraFlags = all(m.Serve.ExtraFlags)
	out.Container.Env = all(m.Container.Env)
	out.Container.Volumes = all(m.Container.Volumes)
	out.Container.Args = all(m.Container.Args)
	out.Container.PreServe = all(m.Container.PreServe)
	out.Container.ModelArg = one(m.Container.ModelArg)
	return &out, err
}

// ContainerEnvFile renders [container] env as a docker --env-file. Docker
// takes each line verbatim after the first '=', so values need no quoting.
func ContainerEnvFile(env []string) string {
	var b strings.Builder
	for _, e := range env {
		b.WriteString(e)
		b.WriteByte('\n')
	}
	return b.String()
}

// PreServeScript wraps the pre_serve commands in a script that aborts on the
// first failure and then execs the server command it is given as arguments.
func PreServeScript(cmds []string) string {
	var b strings.Builder
	b.WriteString("#!/bin/bash\n# Generated by marlin from the profile's [container] pre_serve.\nset -euo pipefail\n")
	for _, c := range cmds {
		b.WriteString(c)
		b.WriteByte('\n')
	}
	b.WriteString("exec \"$@\"\n")
	return b.String()
}

// ContainerLaunch is how a unit applies a profile's [container] table.
type ContainerLaunch struct {
	Args       []string // extra `docker run` flags (env file, mounts, raw args)
	Entrypoint string   // --entrypoint override; "" keeps the unit's default
	PreArgs    []string // arguments placed between the image and the server command
}

// BuildContainerLaunch turns c into docker arguments. envFile and hookFile are
// the host paths of the rendered env file and pre_serve script ("" when the
// profile has none). defaultEntrypoint is the server executable used when
// c.Entrypoint is empty and a pre_serve hook needs to exec it.
func BuildContainerLaunch(c config.ContainerConfig, defaultEntrypoint, envFile, hookFile string) ContainerLaunch {
	var l ContainerLaunch
	if envFile != "" {
		l.Args = append(l.Args, "--env-file", envFile)
	}
	for _, v := range c.Volumes {
		l.Args = append(l.Args, "-v", v)
	}
	l.Args = append(l.Args, c.Args...)

	server := c.Entrypoint
	if server == "" {
		server = defaultEntrypoint
	}
	if hookFile != "" {
		l.Args = append(l.Args, "-v", hookFile+":"+PreServeMount+":ro")
		l.Entrypoint = "/bin/bash"
		l.PreArgs = []string{PreServeMount, server}
	} else if c.Entrypoint != "" {
		l.Entrypoint = c.Entrypoint
	}
	return l
}

// LaunchEnv renders l as <prefix>_CONTAINER_ARGS / _ENTRYPOINT / _PRE_ARGS
// env-file lines for the unit. extraArgs are prepended to the container args.
func LaunchEnv(prefix string, l ContainerLaunch, extraArgs ...string) string {
	var b strings.Builder
	args := append(append([]string{}, extraArgs...), l.Args...)
	if len(args) > 0 {
		fmt.Fprintf(&b, "%s_CONTAINER_ARGS=%s\n", prefix, strings.Join(args, " "))
	}
	if l.Entrypoint != "" {
		fmt.Fprintf(&b, "%s_ENTRYPOINT=%s\n", prefix, l.Entrypoint)
	}
	if len(l.PreArgs) > 0 {
		fmt.Fprintf(&b, "%s_PRE_ARGS=%s\n", prefix, strings.Join(l.PreArgs, " "))
	}
	return b.String()
}
